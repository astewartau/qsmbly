/**
 * Types shared by the new workspace (next.html), the compute worker and the engine bindings.
 *
 * Everything here is a JSDoc typedef: there is no runtime code beyond a few constants. The
 * shapes are the ones the engine bindings (rust-wasm/src/engine.rs on the `engine-bindings`
 * branch, steps 3.1/3.2) produce and consume. `npm run typecheck` checks js/next against them.
 *
 * Where a shape comes from:
 *
 * - Plan, ScanFacts, RunMetadata, Recorded: serde JSON of the qsmxt-engine types, passed through
 *   the bindings as strings (`plan_wasm`, `scan_facts_wasm`, `Engine.plan`, `PageVolumes.begin`
 *   and `.record`). The bindings add `name` and `label` to each plan step.
 * - PageVolumes, EngineObserver: the JS objects `new Engine(volumes, ...)` and `Engine.run(config,
 *   observer)` call back into.
 * - WorkerRequest, WorkerReply: the worker's postMessage protocol.
 *
 * The bindings' own function signatures are generated by wasm-bindgen into wasm/qsm_wasm.d.ts at
 * build time. tsconfig.json maps the module name `qsm-wasm` to that file when it exists, and to
 * js/next/types/qsm-wasm.d.ts (a copy of the subset js/next uses) when it does not; the
 * `Engine` typedef below is the hook. When the bindings export their serde types (`tsify`, §6.1),
 * the typedefs here become re-exports of those.
 *
 * Still in flux (U2 settles these once 3.1/3.2 land):
 * - `Plan.steps[].label` and `Check.problems` arrive with QSMxT #347; older engines omit them.
 * - Items carry no label, units or kind yet (E1), so js/next/items.js names them for now.
 * - The worker replies below are the ones today's UI receives. The new workspace adds the
 *   `volume` reply (an output as a float32 buffer instead of an encoded NIfTI) and the `plan`
 *   request, marked "proposed".
 */

/** The engine's name for a volume: `Item::key()`, e.g. `AcquiredPhase(1)`, `FieldPpm`, `Chi`. */
/** @typedef {string} ItemKey */

/**
 * The facts of one scan that decide what a run can do (qsmxt-engine `ScanFacts`).
 * @typedef {object} ScanFacts
 * @property {[number, number, number]} dims
 * @property {number} n_echoes
 * @property {number[]} echo_times - seconds
 * @property {boolean} has_magnitude
 * @property {number} n_coils
 * @property {boolean} real_imaginary
 * @property {number} field_strength - tesla
 * @property {[number, number, number] | null} b0_dir - null until a loaded scan's affine gives it
 * @property {number[] | null} mese_echo_times
 * @property {boolean} custom_mask
 * @property {boolean} custom_dseg
 * @property {boolean} custom_qsm
 * @property {boolean} custom_r2
 * @property {boolean} custom_r2prime
 */

/**
 * A plan step's stage as serde writes it: a unit variant is a string (`"Load"`), a pass variant an
 * object (`{ "Mask": "Main" }`, `{ "Inversion": "Reliable" }`).
 * @typedef {string | Record<string, 'Main' | 'Reliable'>} Stage
 */

/**
 * @typedef {object} PlanStep
 * @property {Stage} stage
 * @property {string} name - the name its events and cache key use: `mask`, `invert-reliable`, ...
 * @property {string} [label] - for a plan view: `Dipole inversion (reliable pass)` (QSMxT #347)
 * @property {string[]} models - QSM.rs model ids the step runs
 * @property {boolean} host - the step is not in the engine yet; the front end must run it
 */

/**
 * One requirement problem, as data (QSMxT #347).
 * @typedef {object} Problem
 * @property {'error' | 'warning'} severity
 * @property {string | null} setting - config path of the setting asking for the output
 * @property {string | null} implied_by - for a warning, the option that implied the output
 * @property {string} reason
 */

/**
 * @typedef {object} Check
 * @property {string[]} errors - worded for the command line
 * @property {string[]} warnings - worded for the command line
 * @property {Problem[]} [problems] - the same, as data (QSMxT #347)
 */

/**
 * What a run will do (qsmxt-engine `Plan`, plus the bindings' step names and labels).
 * @typedef {object} Plan
 * @property {PlanStep[]} steps
 * @property {string[]} models - every model the run needs, each once
 * @property {number} peak_memory_bytes
 * @property {Check} check
 * @property {string[]} notes
 * @property {boolean} two_pass
 * @property {boolean} motion_corrected
 */

/**
 * The grid a run works on (qsmxt-engine `RunMetadata`).
 * @typedef {object} RunMetadata
 * @property {[number, number, number]} dims
 * @property {[number, number, number]} voxel_size
 * @property {number[]} affine - 16 values, row-major
 * @property {number} n_echoes
 * @property {number[]} echo_times
 * @property {[number, number, number]} b0_direction
 * @property {number} field_strength
 * @property {boolean} has_magnitude
 * @property {[[number, number, number], number[]] | null} [source_geometry]
 * @property {[number, number] | null} [slice_geometry]
 */

/**
 * What the engine recorded besides the volumes (qsmxt-engine `Recorded`): enough for a new
 * engine over the same volumes to carry on with every completed step cached.
 * @typedef {object} Recorded
 * @property {Record<string, [string, string[]]>} steps - step name -> [cache key, output keys]
 * @property {[string, RunMetadata] | null} scan
 * @property {Record<string, unknown>} reports
 * @property {Record<string, Record<string, unknown>>} annotations
 */

/**
 * A volume as the bindings read and write it. Real volumes are float32 (E16); a Float64Array is
 * read but never written. An input may be its NIfTI file.
 * @typedef {Float32Array | Float64Array | Uint8Array | { nifti: Uint8Array, decoded?: Float32Array }} EngineVolume
 */

/**
 * The volume store the engine keeps its volumes in, outside the WASM heap (`PageVolumes` in
 * rust-wasm/src/engine.rs).
 * @typedef {object} PageVolumes
 * @property {(key: ItemKey) => boolean} has
 * @property {(key: ItemKey) => EngineVolume | undefined} get
 * @property {(key: ItemKey, volume: Float32Array | Uint8Array) => void} put
 * @property {(from: ItemKey, to: ItemKey) => boolean} copy
 * @property {(key: ItemKey) => boolean} remove
 * @property {(gridJson: string) => void} [begin] - RunMetadata JSON
 * @property {(recordedJson: string) => void} [record] - Recorded JSON
 */

/** @typedef {'started' | 'cached' | 'finished'} StageEventKind */

/** The bindings' engine over one loaded scan. @typedef {import('qsm-wasm').Engine} Engine */

/**
 * What `Engine.run` reports to. A callback that throws is ignored.
 * @typedef {object} EngineObserver
 * @property {(step: string, algorithm: string | null, event: StageEventKind, text: string | null) => void} [stage]
 * @property {(done: number, total: number) => void} [progress] - of the step being computed
 * @property {(level: 'ERROR' | 'WARN' | 'INFO' | 'DEBUG' | 'TRACE', message: string) => void} [log]
 * @property {(key: ItemKey) => void} [output] - a step kept a volume under `key`
 */

/**
 * A model in QSM.rs's registry (`get_model_registry_wasm`), as far as the UI reads it.
 * @typedef {object} ModelEntry
 * @property {string} id
 * @property {string} name
 * @property {{ name: string, url: string, sha256: string, bytes: number }[]} files
 * @property {string} [license] - not in the registry yet
 */

// ---------------------------------------------------------------------------------------------
// Worker messages
// ---------------------------------------------------------------------------------------------

/**
 * Requests to the compute worker (`{ type, data }`).
 * @typedef {{ type: 'init' }
 *   | { type: 'run', data: RunRequest }
 *   | { type: 'plan', data: { configJson: string, facts: ScanFacts } }
 *   | { type: 'generateCommand' | 'generateMethods' | 'generateConfigToml', data: { configJson: string, maskSection?: string } }
 * } WorkerRequest
 * The `plan` request is proposed for U2: today the worker posts the plan only at the start of a run.
 */

/**
 * A magnitude/phase run, as the worker on `engine-bindings` takes it.
 * @typedef {object} RunRequest
 * @property {ArrayBuffer[]} phaseBuffers - each echo's NIfTI file
 * @property {ArrayBuffer[]} [magnitudeBuffers]
 * @property {number[]} echoTimes - ms
 * @property {number} magField - tesla
 * @property {ArrayBuffer | null} [customMaskBuffer]
 * @property {object} pipelineSettings - today's settings object; the new UI sends a PipelineConfig
 * @property {object[]} [sidecars]
 */

/**
 * Replies from the compute worker.
 * @typedef {{ type: 'initialized', versions: object }
 *   | { type: 'plan', plan: Plan }
 *   | { type: 'stage', step: string, algorithm: string | null, event: StageEventKind, text: string | null }
 *   | { type: 'progress', value: number, text: string }
 *   | { type: 'log', message: string }
 *   | { type: 'stageData', stage: string, data: Uint8Array, description: string, displayNow: boolean, displayRange: [number, number] | null }
 *   | { type: 'volume', key: ItemKey, step: string, buffer: ArrayBufferLike, kind: 'real' | 'mask', grid: RunMetadata }
 *   | { type: 'recorded', recorded: string }
 *   | { type: 'complete', results: object }
 *   | { type: 'error', message: string }
 *   | { type: 'commandResult' | 'methodsResult' | 'configTomlResult', result?: string, error?: string }
 * } WorkerReply
 * `volume` and `recorded` are proposed for U2: the worker posts each output's buffer (shared where
 * the page is cross-origin isolated) and the engine's record, so the page's store (§6.3) holds
 * every volume and a terminated worker loses only the step in progress.
 */

/** The stage events, in the order a computed step reports them. */
export const STAGE_EVENTS = /** @type {const} */ (['started', 'cached', 'finished']);

/** The WASM heap a 32-bit build can address: what the memory gauge compares the plan with. */
export const WASM_HEAP_BYTES = 4 * 1024 ** 3;
